export async function seedDatabase(): Promise<{
  seeded: boolean;
  counts: Record<string, number>;
}> {
  const existingSports = await db.select({ value: count() }).from(sports);
  if (Number(existingSports[0]?.value ?? 0) > 0) {
    return {
      seeded: false,
      counts: {
        sports: Number(existingSports[0]?.value ?? 0),
      },
    };
  }

  await db.insert(sports).values(SEED_SPORTS).onConflictDoNothing();
  await db.insert(coaches).values(SEED_COACHES);
  await db.insert(facilities).values(SEED_FACILITIES);
  await db.insert(competitions).values(SEED_COMPETITIONS);
  await db.insert(trials).values(SEED_TRIALS);
  await db.insert(scholarships).values(SEED_SCHOLARSHIPS);

  return {
    seeded: true,
    counts: {
      sports: SEED_SPORTS.length,
      coaches: SEED_COACHES.length,
      facilities: SEED_FACILITIES.length,
      competitions: SEED_COMPETITIONS.length,
      trials: SEED_TRIALS.length,
      scholarships: SEED_SCHOLARSHIPS.length,
    },
  };
}
